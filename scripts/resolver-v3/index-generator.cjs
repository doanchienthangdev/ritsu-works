#!/usr/bin/env node
'use strict';
/**
 * scripts/resolver-v3/index-generator.cjs — compress full catalog → INDEX.md.
 *
 * Per spec resolver-v3-jit-loading §3 (LOCKED via eng review 2026-05-25):
 *   - Input: knowledge/recipients/*.md (16 files, full catalog)
 *   - Output: knowledge/recipients/INDEX.md (~10-12K tokens target, 15K hard cap)
 *   - Filter: status='active' only (stubs/deprecated/planned hidden)
 *   - Per-entry format: `- <id-without-kind-prefix> :: <when_to_use_1line>`
 *   - Truncation: first-sentence extraction (Q1.1 RESOLUTION); cap at 100 chars
 *   - Header: invoke conventions per kind + drill-down hint to mcp__supabase-ops__resolver_find
 *
 * Usage:
 *   node scripts/resolver-v3/index-generator.cjs            # write INDEX.md
 *   node scripts/resolver-v3/index-generator.cjs --dry-run  # print to stdout
 *   node scripts/resolver-v3/index-generator.cjs --check    # verify size+content
 *
 * Idempotent: same input → same output (deterministic truncation).
 *
 * Exit codes:
 *   0 — success (or dry-run/check clean)
 *   1 — size cap exceeded (>15K tokens)
 *   2 — catalog load error
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const RECIPIENTS_DIR = path.join(REPO_ROOT, 'knowledge', 'recipients');
const INDEX_PATH = path.join(RECIPIENTS_DIR, 'INDEX.md');

const { loadCatalog } = require(path.join(REPO_ROOT, 'scripts/resolver-v2/catalog-loader.cjs'));

const KIND_ORDER = [
  'skill', 'command', 'agent', 'persona', 'mcp',
  'wiki', 'sop', 'capability', 'workflow', 'schedule', 'hook',
  'page', 'view', 'metric', 'runbook', 'external-source',
];

const MAX_SUMMARY_CHARS = 100;
const SHORT_FIRST_SENTENCE_THRESHOLD = 60;  // v3.0.1: if first sentence shorter than this, try to include 2nd
const TOKEN_HARD_CAP = 15000;
const TOKEN_TARGET = 12000;

const HEADER = `<!-- AUTO-GENERATED by scripts/resolver-v3/index-generator.cjs — do not edit -->
<!-- Regenerate: pnpm resolver:index -->
<!-- Generated at: __TIMESTAMP__ -->
<!-- Source files: knowledge/recipients/{skills,commands,agents,personas,mcps,wikis,sops,capabilities,workflows,schedules,hooks,pages,views,metrics,runbooks,external-sources}.md -->

# Resolver Index v3.0

**Total**: __TOTAL_ACTIVE__ active recipients across __KINDS__ kinds. Stubs/deprecated/planned hidden.

**Axis legend** (resolver-plan v1.0; full per-entry axis + enrichment in \`knowledge/recipients/*.md\` and via \`mcp__supabase-ops__resolver_find\`): **content** kinds (page, view, metric, wiki, runbook, external-source) = READ for the answer (carry authority + freshness + grounding); **capability** kinds (skill, command, agent, persona, mcp, sop, workflow, schedule, hook) = RUN to produce it (carry HITL tier + side effect — auto-run Tier A only, surface Tier B+); **meta** = capability (a buildable unit of work).

## Two paths to invoke a recipient

**Path A — DIRECT (0ms, prefer this when sufficient)**: If the 1-line summary below + the invoke convention for the recipient's kind is enough to act, invoke the recipient directly without any drill-down. Most skills, commands, MCP tools, and pages fall here. This is the fast path and the default.

**Path B — DRILL-DOWN via \`mcp__supabase-ops__resolver_find\` (~80-440ms)**: Only when you need ONE of:
- composition graph (which recipients compose with this one — for multi-step workflows)
- recency signal (has this been used recently by my role; success/failure history)
- per-role filter (which recipients my role can invoke)
- disambiguation between 2+ candidates with similar names/summaries
- the FULL when_to_use text (when 1-line summary is too sparse for your decision)

Example: \`mcp__supabase-ops__resolver_find({intent: "onboard customer", kind: "sop", limit: 5})\`
Optional flags: \`include_composition\`, \`include_recency\`, \`role\`. The tool returns top-N candidates with full data. Session model picks by reading — no API key.

\`/resolver query "..."\` delegates to the same MCP tool.

## Invoke conventions (Path A reference)

- \`skill/<id>\` → \`Skill({skill: "<id>"})\`
- \`command/<id>\` → \`/<id>\`
- \`agent/<id>\` → \`Agent({subagent_type: "<id>"})\`
- \`persona/<id>\` → \`@<id>\` or \`/<id>\` (interactive)
- \`mcp/<server>__<tool>\` → \`mcp__<server>__<tool>\`
- \`wiki/<slug>\` → \`Read("wiki/<slug>/source.md")\`
- \`sop/<id>\` → event-triggered, see \`**/sops/<id>/flow.yaml\`
- \`capability/<id>\` → \`Read("wiki/capabilities/<id>/spec.md")\` or \`/cla update <id>\`
- \`workflow/<id>\` → \`workflows/<id>.yaml\`
- \`schedule/<id>\` → pg_cron + dispatcher; see entry for handler
- \`hook/<name>\` → \`.claude/hooks/<name>.md\`
- \`page/<slug>\` → see entry for path
- \`view/<schema>__<name>\` → \`SELECT FROM <schema>.<name>\`
- \`metric/<id>\` → \`mcp__supabase-ops__query\` against source in entry
- \`runbook/<id>\` → \`Read("wiki/runbooks/<id>.md")\`
- \`external-source/<id>\` → entry has source_type + invoke pattern

`;

/**
 * Extract first sentence from when_to_use text.
 * Q1.1 RESOLUTION: first '. ' or '\\n\\n' split, then truncate at word boundary if > MAX.
 */
function firstSentence(text) {
  if (!text || typeof text !== 'string') return '(no description)';
  let s = text.trim();
  if (!s) return '(no description)';  // whitespace-only after trim
  // Paragraph break (\n\n) wins over period boundary — preserves author intent.
  // Use [\s\S] instead of . so we match across newlines.
  const paraMatch = s.match(/^([\s\S]+?)\n\n/);
  if (paraMatch) {
    s = paraMatch[1];
  }
  // Collapse all whitespace (newlines → spaces) — then look for sentence end.
  s = s.replace(/\s+/g, ' ').trim();
  if (!s) return '(no description)';

  // v3.0.1: Try to extract first sentence. If first sentence is short
  // (< SHORT_FIRST_SENTENCE_THRESHOLD chars), try to include the 2nd sentence
  // too (while staying under MAX_SUMMARY_CHARS). This improves Path A viability
  // for entries with terse first-sentences that need more context.
  const firstMatch = s.match(/^(.+?\.)\s/);
  if (firstMatch) {
    const firstSent = firstMatch[1];
    if (firstSent.length < SHORT_FIRST_SENTENCE_THRESHOLD) {
      // Try to append 2nd sentence if total fits under cap
      const rest = s.slice(firstMatch[0].length);
      const secondMatch = rest.match(/^(.+?\.)(\s|$)/);
      if (secondMatch) {
        const combined = firstSent + ' ' + secondMatch[1];
        if (combined.length <= MAX_SUMMARY_CHARS) {
          s = combined;
        } else {
          s = firstSent;
        }
      } else {
        // No 2nd sentence (e.g., text ends here) — keep first
        s = firstSent;
      }
    } else {
      s = firstSent;
    }
  }
  // Truncate if too long (still hard cap)
  if (s.length > MAX_SUMMARY_CHARS) {
    s = s.slice(0, MAX_SUMMARY_CHARS);
    const lastSpace = s.lastIndexOf(' ');
    if (lastSpace > MAX_SUMMARY_CHARS - 20) s = s.slice(0, lastSpace);
    s = s.trimEnd() + '…';
  }
  return s;
}

/**
 * Strip kind prefix from id. 'skill/foo' → 'foo'.
 * Special case: mcp/server__tool stays as is (server__tool).
 */
function stripKindPrefix(id, kind) {
  const prefix = kind + '/';
  if (id.startsWith(prefix)) return id.slice(prefix.length);
  return id;
}

/**
 * Estimate tokens: 1 token ≈ 4 chars (rule of thumb for English+code).
 */
function estimateTokens(text) {
  return Math.ceil(text.length / 4);
}

function isActive(recipient) {
  // Per spec §3.2: filter to status='active' only.
  // Empty/null status treated as active (legacy entries).
  const s = recipient.status;
  return !s || s === 'active';
}

function generate(opts = {}) {
  const catalog = loadCatalog({ skipCache: true });
  const active = catalog.recipients.filter(isActive);

  // Group by kind, preserving KIND_ORDER
  const byKind = new Map();
  for (const k of KIND_ORDER) byKind.set(k, []);
  for (const r of active) {
    if (!byKind.has(r.kind)) byKind.set(r.kind, []);
    byKind.get(r.kind).push(r);
  }

  // Sort within each kind alphabetically (deterministic)
  for (const arr of byKind.values()) {
    arr.sort((a, b) => a.id.localeCompare(b.id));
  }

  const kinds = [...byKind.keys()].filter(k => byKind.get(k).length > 0);
  const totalActive = active.length;

  const lines = [];
  lines.push(
    HEADER
      .replace('__TIMESTAMP__', new Date().toISOString())
      .replace('__TOTAL_ACTIVE__', String(totalActive))
      .replace('__KINDS__', String(kinds.length))
  );

  for (const kind of kinds) {
    const entries = byKind.get(kind);
    lines.push(`## ${kind} (${entries.length})\n`);
    for (const e of entries) {
      const idShort = stripKindPrefix(e.id, kind);
      const summary = firstSentence(e.when_to_use);
      lines.push(`- ${idShort} :: ${summary}`);
    }
    lines.push('');
  }

  const content = lines.join('\n');
  const tokens = estimateTokens(content);

  return {
    content,
    totalActive,
    kindsWithEntries: kinds.length,
    sizeChars: content.length,
    estimatedTokens: tokens,
    overTarget: tokens > TOKEN_TARGET,
    overHardCap: tokens > TOKEN_HARD_CAP,
  };
}

function main() {
  const args = new Set(process.argv.slice(2));
  const dryRun = args.has('--dry-run');
  const check = args.has('--check');

  let result;
  try {
    result = generate();
  } catch (e) {
    console.error(`[ERROR] catalog load failed: ${e.message}`);
    process.exit(2);
  }

  if (result.overHardCap) {
    console.error(
      `[FAIL] INDEX.md would be ${result.estimatedTokens} tokens — exceeds hard cap ${TOKEN_HARD_CAP}.\n` +
      `Tighten per-entry truncation OR exclude a kind from ambient. See spec §3.3.`
    );
    process.exit(1);
  }
  if (result.overTarget && !dryRun) {
    console.warn(
      `[WARN] INDEX.md is ${result.estimatedTokens} tokens — above target ${TOKEN_TARGET} (under hard cap ${TOKEN_HARD_CAP}).\n` +
      `Consider tightening if growth continues.`
    );
  }

  if (check) {
    // Compare against on-disk INDEX.md
    if (!fs.existsSync(INDEX_PATH)) {
      console.error(`[FAIL] INDEX.md missing at ${INDEX_PATH}`);
      process.exit(1);
    }
    const current = fs.readFileSync(INDEX_PATH, 'utf-8');
    // Strip timestamp line for comparison (it changes every run)
    const stripTs = (s) => s.replace(/<!-- Generated at: [^>]+ -->/g, '<!-- Generated at: STRIPPED -->');
    if (stripTs(current) !== stripTs(result.content)) {
      console.error(`[FAIL] INDEX.md is stale (sources changed). Run: pnpm resolver:index`);
      process.exit(1);
    }
    console.log(`[PASS] INDEX.md current (${result.totalActive} active, ${result.estimatedTokens} tokens)`);
    process.exit(0);
  }

  if (dryRun) {
    console.log(result.content);
    console.error(
      `\n[dry-run] would write ${result.sizeChars} chars (~${result.estimatedTokens} tokens), ` +
      `${result.totalActive} active recipients across ${result.kindsWithEntries} kinds`
    );
    process.exit(0);
  }

  fs.writeFileSync(INDEX_PATH, result.content, 'utf-8');
  console.log(
    `[OK] wrote ${INDEX_PATH} (${result.sizeChars} chars, ~${result.estimatedTokens} tokens, ` +
    `${result.totalActive} active recipients across ${result.kindsWithEntries} kinds)`
  );
  process.exit(0);
}

module.exports = {
  generate,
  firstSentence,
  stripKindPrefix,
  estimateTokens,
  isActive,
  KIND_ORDER,
  MAX_SUMMARY_CHARS,
  TOKEN_HARD_CAP,
  TOKEN_TARGET,
  INDEX_PATH,
};

if (require.main === module) {
  main();
}
